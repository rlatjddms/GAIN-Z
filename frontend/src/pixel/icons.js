// 아이콘을 칠할 칸 목록 [[x, y], ...]
export function iconCells(name) {
  const rows = PIXEL_ICONS[name] || []
  const cells = []
  rows.forEach((row, y) => [...row].forEach((c, x) => { if (c === 'x') cells.push([x, y]) }))
  return cells
}
